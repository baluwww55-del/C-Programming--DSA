// Functions :
// types of functions 
// we analyze algorithms using functions :

// there are several types of functions which we used to get notations . 

// 1) decreasing functions :
// n = increasing  =  f(n)decreasing :
// eg f(n) = 1/n n = 2 ---> 1/2
// eg f(n) = 1/n n = 4 ---> 1/4
// eg f(n) = 1/n n^2 = 2 --> 1/4
// this is known as decreasing functions if n increrasing then f(n) is decreasing . 


// 2) Increasing functions :
// n increasing = f(n) increasing :
// eg n^2 if n = 2 then n^2 = f(n) = 4 
// eg n^2 if n = 5 then n^2 = f(n) = 25 
// this is known as increasing functions if n increasingn the f(n) is also increasing . 

// there are many types of functions :
// 1) constant functions :
// functions which have fixed value known as constant function . 
// eg : 2n^0 , 3n^0 .... etc . 

// 2) logarithmic functions :
// functions which contain logs it is known as logarithmic functions . 
// eg : logn , loglogn , nlogn,....etc . 

// 3) linear functions :
// linear functions which denote linearly counting series . 
// eg : n , n+2, n+3...etc . 

// 4) quadratic functions : 
// quadratic functions which is polynomial function of degree is 2 . 
// eg : 2n^2 , 3n^3....etc . 

// 5) cubic functions :
// cubic functions is the functions which is polynomial function of degree is 3 . 
// eg : 2n^3 , 3n^3 .... etc . 

// 6) polynomial functions :
// polynomial functions is the functions which is polynomial function of degree is n . 
// eg : a^n , b^n-1 ....etc . 

// 7) exponential functions : 
// exponential functions is the functions which is polynomial function of degree is n . 
// eg : e^x , 2^n ... etc . 

// these are the common functions which is used to represent the time complexity of an algorithm . 
