// Asymptotic notations :
// majorly there are five types of asymptotic notations . 

// 1) Big O :
// 2) Big omega :
// 3) theta :
// 4) small o :
// 5) small omega :

// 1) Big O : 
// Big O is the notation used to find the tightest or maximum time taken by an algrithm to execute / to get output .
// F(n) <= c*g(n) 
// F(n) = g(n) . 

// 2) Big omega :
// Big omega is the notation which is used to find the tightest lower bound or minimum time taken by an algorithm to execute / to get output . 
// F(n) >= c*g(n)

// 3) theta :
//  theta is the notation which is used to find the exact / average time taken by an algorithm to execute / to get output . 

// 4) small o :
// small o is the notation which is used to find the upper bound of an algorithm but it is not tightest bound. 
// F(n) < c*g(n) (" difference between the big O and small is all about equal ")

// 5) small omega :
// small omega is the notation which is used to find the lower bound of an algorithm but it is not tightest bound . 
// F(n) > c*g(n) (" difference between the big omega and small omega is all about equal ")

// these are the basic example of the asymptotic notations which is used to find the time complexity of an algorithm . 
